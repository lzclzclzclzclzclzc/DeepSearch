import assert from "node:assert/strict";
const origin = process.env.TEST_BASE_URL || "http://localhost:3200";
const home = await fetch(origin);
assert.equal(home.status, 200);
assert.equal(home.headers.get("referrer-policy"), "no-referrer");
const icon = await fetch(`${origin}/brand/icon-32.png`);
assert.equal(icon.status, 200);
assert.match(icon.headers.get("content-type") || "", /image\/png/);
const iconBytes = Buffer.from(await icon.arrayBuffer());
assert.ok(iconBytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])));
const cookie = home.headers.get("set-cookie")?.split(";")[0];
assert.ok(cookie);
const headers = { Origin: origin, Cookie: cookie, "Content-Type": "application/json" };
const credential = "smoke-key-not-real-never-used-for-search";
const saved = await fetch(`${origin}/api/session/config`, { method: "POST", headers, body: JSON.stringify({ apiKey: credential }) });
assert.equal(saved.status, 200);
assert.deepEqual(await saved.json(), { configured: true, source: "personal", state: "saved" });
const read = await fetch(`${origin}/api/session/config`, { headers });
const statusText = await read.text(); assert.ok(!statusText.includes(credential));
assert.equal(JSON.parse(statusText).source, "personal");
const stranger = await fetch(`${origin}/api/session/config`); assert.equal(stranger.status, 410);
const forbidden = await fetch(`${origin}/api/session/config`, { method: "POST", headers: { ...headers, Origin: "https://evil.example" }, body: JSON.stringify({ apiKey: credential }) });
assert.equal(forbidden.status, 403);
const cleared = await fetch(`${origin}/api/session/data`, { method: "DELETE", headers }); assert.equal(cleared.status, 200);
const after = await fetch(`${origin}/api/session/config`, { headers }); assert.equal((await after.json()).source, "none");
const health = await fetch(`${origin}/api/health`); assert.equal(health.status, 200);
console.log("Production container smoke passed: page, headers, session, key save/isolation/removal, Origin checks, health. No supplier requests.");
